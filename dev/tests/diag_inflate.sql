-- Diagnóstico: o INFLATE do package descomprime FlateDecode de verdade?
--
-- Vetores comprimidos pelo zlib fora do banco; o resultado é comparado BYTE A
-- BYTE com o conteúdo original, também embutido. Um inflate errado não "quase
-- funciona": produz alguns bytes plausíveis e lixo depois.
--
-- Os quatro casos cobrem os três tipos de bloco do DEFLATE mais a armadilha do
-- LZ77, que nenhum corpus ingênuo exercita junto:
--   Huffman dinâmico ... uma xref em stream de verdade
--   Huffman fixo ....... texto curto
--   armazenado ......... dado aleatório, em que o compressor desiste
--   cópia sobreposta ... o mesmo byte repetido, distância 1
--
-- O TETO DE SAÍDA é deliberadamente baixo (4 KB). Nenhum destes casos passa de
-- 688 bytes, então -20893 aqui significa laço desgovernado — e a mensagem diz
-- em quantos bytes parou. É o que separa "o inflate está errado" de "o inflate
-- está certo e o consumo é legítimo": sem o teto, a diferença aparecia como
-- ORA-04036, que não distingue as duas.
--
-- Execute na SQL Window do PL/SQL Developer (F8).
--------------------------------------------------------------------------------

