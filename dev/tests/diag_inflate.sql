  l_ok  PLS_INTEGER := 0;
  l_mau PLS_INTEGER := 0;

  PROCEDURE conferir(p_nome VARCHAR2, p_zlib RAW, p_esperado RAW) IS
    l_src BLOB;
    l_exp BLOB;
    l_out BLOB;
    l_t   PLS_INTEGER;
  BEGIN
    DBMS_LOB.CREATETEMPORARY(l_src, TRUE);
    DBMS_LOB.CREATETEMPORARY(l_exp, TRUE);
    DBMS_LOB.WRITEAPPEND(l_src, UTL_RAW.LENGTH(p_zlib), p_zlib);
    DBMS_LOB.WRITEAPPEND(l_exp, UTL_RAW.LENGTH(p_esperado), p_esperado);

    l_out := PL_FPDF.FlateDecode(l_src, co_teto);
    l_t   := NVL(DBMS_LOB.GETLENGTH(l_out), 0);

    IF l_t != DBMS_LOB.GETLENGTH(l_exp) THEN
      l_mau := l_mau + 1;
      DBMS_OUTPUT.PUT_LINE('  [FAIL] ' || p_nome || ': ' || l_t
                           || ' bytes, esperado ' || DBMS_LOB.GETLENGTH(l_exp));
    -- DBMS_LOB.COMPARE, e nao STANDARD_HASH: aquele nao aceita LOB (ORA-00902)
    ELSIF DBMS_LOB.COMPARE(l_out, l_exp) != 0 THEN
      l_mau := l_mau + 1;
      DBMS_OUTPUT.PUT_LINE('  [FAIL] ' || p_nome
                           || ': tamanho certo mas o conteudo DIVERGE');
    ELSE
      l_ok := l_ok + 1;
      DBMS_OUTPUT.PUT_LINE('  [PASS] ' || p_nome || ': ' || l_t
                           || ' bytes, conteudo confere byte a byte');
    END IF;
    DBMS_LOB.FREETEMPORARY(l_src);
    DBMS_LOB.FREETEMPORARY(l_exp);
    DBMS_LOB.FREETEMPORARY(l_out);
  EXCEPTION
    WHEN OTHERS THEN
      l_mau := l_mau + 1;
      DBMS_OUTPUT.PUT_LINE('  [FAIL] ' || p_nome || ': ' || SQLERRM);
